function _simos_dispatch_call(mod, src, path::Tuple, posargs::Vector{Any}, kwargs::Vector{Expr}, payload_expr)
    if path == (:system, :init)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos system.init is engine-only and does not accept session labels. Use `@simos session.init(...)`.")
        args = Any[_simos_kw_to_assign.(kwargs)...]
        return _simos_init(mod, src, args)
    elseif path == (:system, :reset)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos system.reset accepts only keyword arguments.")
        args = Any[_simos_kw_to_assign.(kwargs)...]
        return _simos_reset(mod, src, args)
    elseif path == (:project, :current)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos project.current accepts no positional arguments.")
        return _simos_project_current(mod, src)
    elseif path == (:settings, :get)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_get(mod, src, posargs, kwargs)
    elseif path == (:settings, :has)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_has(mod, src, posargs, kwargs)
    elseif path == (:settings, :require)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_require(mod, src, posargs, kwargs)
    elseif path == (:settings, :explain)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_explain(mod, src, posargs, kwargs)
    elseif path == (:settings, :layers)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos settings.layers accepts no positional arguments.")
        return _simos_settings_layers(mod, src)
    elseif path == (:settings, :snapshot)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos settings.snapshot accepts no positional arguments.")
        return _simos_settings_snapshot(mod, src, kwargs)
    elseif path == (:settings, :set)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_set(mod, src, posargs, kwargs)
    elseif path == (:settings, :unset)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_unset(mod, src, posargs, kwargs)
    elseif path == (:settings, :merge)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_merge(mod, src, posargs, kwargs)
    elseif path == (:settings, :clear)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos settings.clear accepts no positional arguments.")
        return _simos_settings_clear(mod, src, kwargs)
    elseif path == (:settings, :source, :add_json)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_source_add_json(mod, src, posargs, kwargs)
    elseif path == (:settings, :source, :add_args)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_source_add_args(mod, src, posargs, kwargs)
    elseif path == (:settings, :source, :reload)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_source_reload(mod, src, posargs, kwargs)
    elseif path == (:settings, :source, :remove)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_source_remove(mod, src, posargs)
    elseif path == (:settings, :source, :list)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos settings.source.list accepts no positional arguments.")
        return _simos_settings_source_list(mod, src)
    elseif path == (:settings, :tracking, :on)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos settings.tracking.on accepts no positional arguments.")
        return _simos_settings_tracking_on(mod, src)
    elseif path == (:settings, :tracking, :off)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos settings.tracking.off accepts no positional arguments.")
        return _simos_settings_tracking_off(mod, src)
    elseif path == (:settings, :registry, :register)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_registry_register(mod, src, posargs, kwargs)
    elseif path == (:settings, :registry, :unregister)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_settings_registry_unregister(mod, src, posargs)
    elseif path == (:settings, :registry, :list)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos settings.registry.list accepts no positional arguments.")
        return _simos_settings_registry_list(mod, src)
    elseif path == (:sqlite, :path)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos sqlite.path accepts no positional arguments.")
        return _simos_sqlite_path(mod, src)
    elseif path == (:sqlite, :open)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos sqlite.open accepts only keyword arguments (e.g. `sync=:refresh`).")
        return _simos_sqlite_open(mod, src, kwargs)
    elseif path == (:sqlite, :current)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos sqlite.current accepts no positional arguments.")
        return _simos_sqlite_current(mod, src)
    elseif path == (:sqlite, :execute)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_sqlite_execute(mod, src, posargs)
    elseif path == (:sqlite, :refresh)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos sqlite.refresh accepts no positional arguments.")
        return _simos_sqlite_refresh(mod, src)
    elseif path == (:sqlite, :rebuild)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos sqlite.rebuild accepts no positional arguments.")
        return _simos_sqlite_rebuild(mod, src)
    elseif path == (:sqlite, :close)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos sqlite.close accepts no positional arguments.")
        return _simos_sqlite_close(mod, src)
    elseif path == (:blob, :meta)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_blob_meta(mod, src, posargs)
    elseif path == (:session, :init)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_session_init(mod, src, posargs)
    elseif path == (:session, :commit)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_commit(mod, src, posargs)
    elseif path == (:session, :queue)
        _simos_disallow_do(path, payload_expr)
        return _simos_batch_commit(mod, src, posargs, kwargs)
    elseif path == (:session, :close)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_finalize(mod, src, posargs)
    elseif path == (:stage, :blob)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_store(mod, src, posargs)
    elseif path == (:stage, :hash)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_hash(mod, src, posargs)
    elseif path == (:stage, :inline)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_inline(mod, src, posargs)
    elseif path == (:stage, :meta)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos stage.meta accepts only keyword arguments.")
        return _simos_meta(mod, src, Any[_simos_kw_to_assign.(kwargs)...])
    elseif path == (:scope, :capture)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_capture(mod, src, posargs)
    elseif path == (:scope, :bind)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_expand(mod, src, posargs)
    elseif path == (:shared, :capture)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_shared_capture(mod, src, posargs)
    elseif path == (:shared, :bind)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_shared_bind(mod, src, posargs)
    elseif path == (:shared, :merge)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_shared_merge(mod, src, posargs)
    elseif path == (:shared, :keys)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_shared_keys(mod, src, posargs)
    elseif path == (:shared, :has)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_shared_has(mod, src, posargs)
    elseif path == (:shared, :drop)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_shared_drop(mod, src, posargs)
    elseif path == (:shared, :clear)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        return _simos_shared_clear(mod, src, posargs)
    elseif path == (:context, :capture)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        isempty(posargs) || error("@simos context.capture accepts no positional arguments.")
        return _simos_context_capture(mod, src)
    elseif path == (:context, :resolve)
        _simos_disallow_kwargs(path, kwargs)
        _simos_disallow_do(path, payload_expr)
        length(posargs) == 1 || error("@simos context.resolve expects exactly one argument (RecordRef or hash string).")
        return _simos_context_resolve(mod, src, posargs)
    elseif path == (:cache, :key)
        _simos_disallow_do(path, payload_expr)
        args = Any[posargs...]
        append!(args, _simos_kw_to_assign.(kwargs))
        return _simos_ctx_hash(mod, src, args)
    elseif path == (:cache, :remember)
        length(posargs) in (2, 3) || error("@simos cache.remember expects `(ctx_hash, target)` plus a `do` block or explicit payload expression.")
        ctx_hash_expr = posargs[1]
        target_expr = posargs[2]
        if !isnothing(payload_expr) && length(posargs) != 2
            error("@simos cache.remember do form expects exactly `(ctx_hash, target)` positional arguments.")
        end
        if isnothing(payload_expr) && length(posargs) == 2
            error("@simos cache.remember requires a `do` block or an explicit third payload expression.")
        end
        payload = isnothing(payload_expr) ? posargs[3] : payload_expr

        args = Any[ctx_hash_expr]
        isempty(kwargs) || push!(args, _simos_kwargs_tuple_expr(kwargs))
        push!(args, Expr(:(=), target_expr, payload))
        return _simos_remember(mod, src, args)
    else
        error("Unknown @simos command `$(_simos_path_str(path))`. Valid commands: $(_simos_command_list_str())")
    end
end

